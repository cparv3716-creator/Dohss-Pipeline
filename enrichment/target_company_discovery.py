def normalize_company_name(name):
    return " ".join(str(name or "").lower().strip().split())


def get_seed_companies():
    """Return the full seed company list (copies, safe to mutate)."""
    return [dict(c) for c in _SEED_COMPANIES]


def discover_target_companies(db_path, institutes=None, limit=300, config=None):
    """
    Populate target_companies and company_roles from seed data.

    institutes: optional list of institute keys to filter by (e.g. ['dse','isi']).
                If None or empty, all seed companies are included.
    Returns (companies_upserted, roles_inserted) counts.
    """
    from database import db

    db.init_db(db_path)

    inst_filter = None
    if institutes:
        inst_filter = {i.lower().strip() for i in institutes}

    companies_saved = 0
    roles_saved = 0

    for seed in _SEED_COMPANIES[:limit]:
        # Institute filter
        if inst_filter:
            seed_insts = {i.lower() for i in (seed.get("source_institutes") or [])}
            if not seed_insts.intersection(inst_filter):
                continue

        if db.upsert_target_company(db_path, seed):
            companies_saved += 1
            logger.debug("Upserted target company: %s", seed["company"])

        # Get the company id
        conn = db.get_connection(db_path)
        row = conn.execute(
            "SELECT id FROM target_companies WHERE normalized_company=?",
            (normalize_company_name(seed["company"]),),
        ).fetchone()
        conn.close()
        company_id = row["id"] if row else None

        for role_title in (seed.get("specific_roles_offered") or []):
            # Determine role_family
            rf = _infer_role_family(role_title, seed.get("likely_role_families") or [])
            for inst in (seed.get("source_institutes") or []):
                if inst_filter and inst.lower() not in inst_filter:
                    continue
                if db.insert_company_role(db_path, {
                    "company_id": company_id,
                    "company": seed["company"],
                    "role_title": role_title,
                    "role_family": rf,
                    "source_institute": inst,
                    "evidence_url": seed.get("evidence_url", ""),
                    "confidence_score": seed.get("confidence_score", 70),
                    "notes": seed.get("notes", ""),
                }):
                    roles_saved += 1

    return companies_saved, roles_saved


def _infer_role_family(role_title, preferred_families):
    """Return the best role_family for a role_title string."""
    title_lower = role_title.lower()
    for family, roles in ROLE_FAMILIES.items():
        for r in roles:
            if r.lower() in title_lower or title_lower in r.lower():
                return family
    if preferred_families:
        return preferred_families[0]
    return "data_analytics"
